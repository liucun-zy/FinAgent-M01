"""One typed M01 tool contract, validated at independent persistence seams.

OS-01: Pydantic supplies schema and decoding. The save envelope deliberately
uses Any items until partition_extraction validates each entity/claim separately.
"""
from __future__ import annotations

from copy import deepcopy
from functools import lru_cache
from typing import Annotated, Any, Generic, Literal, TypeVar

from pydantic import BaseModel, ConfigDict, Field, TypeAdapter


class InputModel(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True)


class LookupMention(InputModel):
    name: str = Field(min_length=1)
    type: str | None = None
    local_entity_id: str | None = None


class LookupEntitiesInput(InputModel):
    mentions: list[LookupMention]


class ContextRequest(InputModel):
    window_id: str
    relation: Literal["neighbors", "section", "table_context", "referenced"]
    target_ref_or_query: str = ""


class ReadContextInput(InputModel):
    requests: list[ContextRequest]


class EntityCore(InputModel):
    local_entity_id: str
    surface_name: str
    evidence_ref_ids: list[str]
    type_hint: str = ""
    description: str = ""
    identity_clues: dict[str, Any] = Field(default_factory=dict,
        description="主体自己的稳定业务标识；不放关联对象或一般属性")
    existing_entity_id: str | None = None
    aliases: list[str] = Field(default_factory=list)
    context: str = ""


class EntityMention(EntityCore):
    field_evidence: dict[str, list[str]] = Field(default_factory=dict)


class ScalarValue(InputModel):
    kind: Literal["number", "date", "text"]
    normalized: str
    unit: str = ""


class EntityValue(InputModel):
    kind: Literal["entity"]
    local_entity_id: str = ""
    normalized: str = ""
    unit: str = ""


class RangeValue(InputModel):
    kind: Literal["range"]
    lower: str = ""
    upper: str = ""
    normalized: str = ""
    unit: str = ""


Value = ScalarValue | EntityValue | RangeValue
ExistingTime = str | dict[str, Any]


class RawValue(InputModel):
    text: str
    unit: str | None = None


class TemporalEvent(InputModel):
    event: str
    time: ExistingTime | None = None


class TemporalAnnotations(InputModel):
    events: list[TemporalEvent] = Field(default_factory=list)


class QualifierEntityRef(InputModel):
    path: list[str | int] = Field(min_length=1)
    local_entity_id: str


class ClaimCore(InputModel):
    subject_local_id: str
    predicate: str
    statement: str
    evidence_ref_ids: list[str]
    local_claim_id: str = ""
    source_version_id: str = ""
    description: str = ""
    value: Value | None = None
    raw_value: RawValue | str | None = Field(default=None,
        description="可省；模型的原写法解释。逐字原文由 evidence 位置回读，不以规范值反填")
    qualifiers: dict[str, Any] = Field(default_factory=dict,
        description="必要业务条件、产品、税口径、期间、情态；不放表格坐标")
    effective_time: ExistingTime | None = Field(default=None,
        description="仅业务适用时间；未知null，不能用文档或事件日期回填")


class SourceClaim(ClaimCore):
    temporal: TemporalAnnotations | None = None
    field_evidence: dict[str, list[str]] = Field(default_factory=dict)
    qualifier_entity_refs: list[QualifierEntityRef] = Field(default_factory=list)


E = TypeVar("E")
C = TypeVar("C")


class ExtractionBatch(InputModel, Generic[E, C]):
    entities: list[E]
    claims: list[C]
    processed_window_ids: list[str]
    unresolved: list[dict[str, Any] | str]


class SaveExtractionInput(ExtractionBatch[E, C], Generic[E, C]):
    window_group_id: str
    retry_claim_indices: list[Annotated[int, Field(ge=0)]] | None = None


TOOL_TYPES = {
    "read_context": ReadContextInput,
    "lookup_entities": LookupEntitiesInput,
    "save_extraction": SaveExtractionInput[EntityMention, SourceClaim],
}
DESCRIPTIONS = {
    "read_context": "一次批量补读实际来源内容；不重复返回已读证据。",
    "lookup_entities": "按具体提及名称检索已有实体身份候选；合法无候选与参数错误分开。",
    "save_extraction": "逐条保存独立claim，返回accepted/rejected及辅助warnings；仅失败claim需修正。",
}


@lru_cache
def adapter(kind):
    return TypeAdapter(kind)


def decode_tool(name, arguments):
    # The exact same outer contract is used without recursively validating facts.
    # Otherwise one bad claim would prevent all accepted siblings from saving.
    kind = SaveExtractionInput[Any, Any] if name == "save_extraction" else TOOL_TYPES[name]
    return adapter(kind).validate_python(arguments)


def decode_item(kind, value):
    return adapter(kind).validate_python(value).model_dump(exclude_unset=True)


def tool_specs():
    # Local refs are generated by Pydantic, not a second handwritten contract.
    # Drop display titles to keep the provider's input budget focused on fields.
    def compact(value):
        if isinstance(value, dict):
            return {k: compact(v) for k, v in value.items() if k != "title"}
        if isinstance(value, list):
            return [compact(v) for v in value]
        return value
    return [{"name": name, "description": DESCRIPTIONS[name],
             "parameters": compact(kind.model_json_schema())}
            for name, kind in TOOL_TYPES.items()]
